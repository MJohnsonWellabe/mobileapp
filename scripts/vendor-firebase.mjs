// Bundles the Firebase Web SDK into assets/vendor/firebase.js, which is committed.
//
//     npm run vendor:firebase
//
// Why vendor at all, when docs/02-architecture.md prefers CDN imports from gstatic:
//
//   1. The app then has no third-party runtime dependency. A demo that dies because
//      gstatic is slow, blocked by conference Wi-Fi, or reachable but rate-limited is
//      a demo that dies on stage. Everything the app needs ships from the same origin
//      as the app.
//   2. It is testable. The build environment's egress proxy blocks gstatic outright,
//      so with CDN imports the app cannot be rendered or screenshotted locally at all
//      — which would mean the visual QA loop in docs/07 reviews something other than
//      what ships.
//   3. Version drift stops being possible. The pinned URL in three separate imports
//      was one careless edit away from mixing SDK versions.
//
// This is NOT the kind of build step docs/02 warns about. GitHub Pages still serves
// committed static files, nothing builds in CI, and the app has no bundler at runtime.
// The output is a committed artifact, regenerated by hand on the rare occasion the SDK
// version changes. See setup/GITHUB-SETUP.md "If a build step ever gets added".
//
// One bundle, not three. Firestore and Storage both look up the initialized app in a
// registry inside @firebase/app; bundling them separately would give each its own copy
// of that registry, and getFirestore(app) would not find the app that initializeApp()
// registered.

import esbuild from 'esbuild';
import fs from 'node:fs';
import path from 'node:path';

const OUT = 'assets/vendor/firebase.js';
const ENTRY = 'scripts/.firebase-entry.js';

// Renaming Storage's `ref` keeps the flat re-export collision-free and makes call
// sites read unambiguously — `storageRef(...)` next to Firestore's `doc(...)`.
const entry = `
export { initializeApp, getApp, getApps } from 'firebase/app';
export * from 'firebase/firestore';
export {
  getStorage,
  ref as storageRef,
  uploadBytes,
  getDownloadURL,
  connectStorageEmulator,
} from 'firebase/storage';
`;

fs.mkdirSync(path.dirname(OUT), { recursive: true });
fs.writeFileSync(ENTRY, entry);

try {
  const version = JSON.parse(
    fs.readFileSync('node_modules/firebase/package.json', 'utf8'),
  ).version;

  await esbuild.build({
    entryPoints: [ENTRY],
    outfile: OUT,
    bundle: true,
    format: 'esm',
    platform: 'browser',
    target: ['es2020'],
    minify: true,
    legalComments: 'none',
    banner: {
      js:
        `// Firebase Web SDK ${version}, bundled from npm by scripts/vendor-firebase.mjs.\n` +
        `// Generated file — do not edit. Regenerate with: npm run vendor:firebase\n` +
        `// @license Apache-2.0 https://github.com/firebase/firebase-js-sdk/blob/master/LICENSE\n`,
    },
  });

  const kb = Math.round(fs.statSync(OUT).size / 1024);
  console.log(`wrote ${OUT} — Firebase ${version}, ${kb} KB`);
} finally {
  fs.rmSync(ENTRY, { force: true });
}
